def generate_330_kb():
    print("=" * 70)
    print("موتور تولید جامع پایگاه دانش ۳۳۰ گرایشی هیدروما")
    print("=" * 70)
    
    # بارگذاری دانش موجود برای حفظ گرایش‌های دستی قبلی
    existing_kb = {}
    if KB_FILE.exists():
        existing_kb = json.loads(KB_FILE.read_text(encoding="utf-8"))
        print(f"\n✅ پایگاه دانش فعلی بارگذاری شد: {len(existing_kb)} گرایش")
    
    new_kb = {}
    total_generated = 0
    
    for domain_code, specialties in DOMAINS.items():
        templates = DOMAIN_INDICATOR_TEMPLATES[domain_code]
        
        for idx, name_fa in enumerate(specialties, start=1):
            spec_id = f"{domain_code}{idx:03d}"
            
            # اگر از قبل با جزئیات کامل وجود دارد، حفظش کن
            if spec_id in existing_kb and len(existing_kb[spec_id].get("indicators", [])) >= 2:
                new_kb[spec_id] = existing_kb[spec_id]
                continue
                
            # تولید گرایش جدید با قالب تخصصی
            indicators = []
            for i, tmpl in enumerate(templates):
                indicators.append({
                    "id": f"{spec_id}_IND{i+1:02d}",
                    "name": tmpl["name"],
                    "symbol": tmpl["symbol"],
                    "unit": tmpl["unit"],
                    "formula": tmpl["formula"],
                    "default_value": tmpl["default_value"],
                    "threshold": tmpl["threshold"]
                })
                
            new_kb[spec_id] = {
                "name": name_fa,
                "domain": domain_code,
                "indicators": indicators,
                "formulas": {
                    "domain_model": {
                        "name": f"مدل محاسباتی {name_fa}",
                        "formula": templates[0]["formula"],
                        "parameters": {"P1": "پارامتر ورودی ۱", "P2": "پارامتر ورودی ۲"}
                    }
                },
                "hydroma_role": {
                    "algorithms": ["H18", "H22", "H25"],
                    "inputs": ["داده‌های اقلیمی", "داده‌های خاک", "داده‌های مدیریتی"],
                    "outputs": [f"شاخص‌های پایداری {name_fa}"]
                }
            }
            total_generated += 1
            
    # ذخیره نهایی
    KB_FILE.write_text(
        json.dumps(new_kb, ensure_ascii=False, indent=2),
        encoding="utf-8"
    )
    
    print(f"\n🚀 تولید {total_generated} گرایش جدید انجام شد.")
    print(f"✅ پایگاه دانش نهایی ذخیره شد: {len(new_kb)} گرایش")
    
    # آمار حوزه‌ها
    print("\n📊 توزیع نهایی ۳۳۰ گرایش:")
    for domain in DOMAINS.keys():
        count = sum(1 for k in new_kb if k.startswith(domain))
        print(f"   🔹 {domain}: {count} گرایش")
        
    print("=" * 70)

if __name__ == "__main__":
    generate_330_kb()