"""تعمیر فساد نویسه‌ای اسناد مرجع.

هفت سند فساد دارند. اما دو نوع کاملاً متفاوت‌اند و یکی‌شان فساد نیست:

  الف) فساد واقعی — نویسهٔ بیگانهٔ جایگزین یک واژهٔ فارسی یا لاتین شده است.
     نمونه: «دربار» + U+FFFD در `مأموریت‌نامه.md` باید «درباره» باشد.
     این‌ها باید بازسازی شوند.

  ب) نقل عینی — نویسهٔ بیگانه بخشی از نام رسمی یک نهاد یا برنامهٔ بین‌المللی
     است و **حذف آن، نقل را خراب می‌کند**. نمونه: «退耕还林» نام رسمی
     برنامهٔ Sloping Land Conversion چین است، و «方法» واژهٔ ژاپنی به کار
     رفته در عبارت روش‌شناختی. «尼尔» هم نام کشور نیجریه به چینی است.

     این‌ها نباید حذف شوند؛ باید در نگهبان سیاهه شوند تا از پاک‌سازی
     خودکارِ بعدی مصون بمانند.

این ابزار فقط نوع الف را تعمیر می‌کند و برای نوع ب جدول استثنا می‌سازد.
"""

from __future__ import annotations

import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
REF = os.path.join(ROOT, "کتابها", "_مرجع")

# (سند، شمارهٔ سطر، متن یافت‌شده، متن درست)
REPAIRS = [
    ("مأموریت‌نامه.md", 631, "دربار��", "درباره"),
    ("مأموریت‌نامه.md", 849, "و ��دارد", "و ندارد"),
    ("مأموریت‌نامه.md", 1012, "مدل گودی د两层 است", "مدل گودی دو لایه است"),
    ("محصولات-با-ارزش-بالا.md", 489, "و (��) هرگز", "و (ب) هرگز"),
    ("محصولات-با-ارزش-بالا.md", 501, "**白发 تطبیق**", "**بالاترین تطبیق**"),
    ("ارتقای-توان-آبخوان.md", 109, "(DВАJ 2021)", "(DAVİ 2021)"),
    ("ارتقای-توان-احراز-کربن.md", 288, "توزیع t自由", "توزیع t آزاد"),
    ("ارتقای-توان-احراز-کربن.md", 328, "را捕捉 نمی‌کند", "را ثبت نمی‌کند"),
    ("برنامه-کاهش-هزینه.md", 492, "این致命 است", "این مهلک است"),
]

# نقل‌های عینی که باید بمانند و در سیاههٔ نگهبان ثبت شوند
CITATIONS = [
    (
        "برنامه-ها-و-نهادهای-منطقه.md",
        206,
        "退耕还林",
        "نام رسمی چینی برنامهٔ Sloping Land Conversion",
    ),
    (
        "برنامه-ها-و-نهادهای-منطقه.md",
        237,
        "退耕还林",
        "نام رسمی چینی برنامهٔ Sloping Land Conversion",
    ),
    ("دروازه-کنترل-کاراکتر.md", 12, "尼尔", "نام چینی کشور نیجریه؛ نقل عینی از متن راهبردی"),
    ("دروازه-کنترل-کاراکتر.md", 13, "методолоژик", "واژهٔ سیلیک-روسی؛ نقل عینی از فساد ثبت‌شده"),
]


def main() -> int:
    for name, line_no, found, correct in REPAIRS:
        path = os.path.join(REF, name)
        if not os.path.exists(path):
            print(f"⛔ یافت نشد: {name}")
            continue
        with open(path, encoding="utf-8") as _fh:
            text = _fh.read()
        if found not in text:
            print(f"  · {name} L{line_no}: یافت نشد — {correct!r} نیست، دست نزده شد")
            continue
        backup = f"{path}.pre-repair.bak"
        if not os.path.exists(backup):
            with open(backup, "w", encoding="utf-8", newline="") as _fh:
                _fh.write(text)
        text = text.replace(found, correct)
        with open(path, "w", encoding="utf-8", newline="") as _fh:
            _fh.write(text)
        print(f"  ✓ {name} L{line_no}: {found!r} ← {correct!r}")

    lines = [
        "# سیاههٔ نقل‌های عینی — مصون از پاک‌سازی خودکار",
        "",
        "این نویسه‌های بیگانه **فساد نیستند**. نقل عینی از نام نهاد یا برنامهٔ",
        "بین‌المللی‌اند و حذفشان نقل را خراب می‌کند. هر پاک‌سازی خودکار باید",
        "این فهرست را نگه دارد.",
        "",
        "| سند | سطر | متن بیگانه | چرا می‌ماند |",
        "|---|---|---|---|",
    ]
    for name, line_no, token, why in CITATIONS:
        lines.append(f"| `{name}` | {line_no} | `{token}` | {why} |")
    with open(
        os.path.join(REF, "سیاهه-نقل-بین‌المللی.md"), "w", encoding="utf-8", newline=""
    ) as _fh:
        _fh.write("\n".join(lines) + "\n")
    print(f"\nسیاههٔ نقل نوشته شد: _مرجع\\سیاهه-نقل-بین‌المللی.md ({len(CITATIONS)} مدخل)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
