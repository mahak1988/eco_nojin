"""Regenerate the engine model-maturity triage table (P10, task 1).

The registry (``engine/models/registry.py``) is the source of truth for the 70
registered models: 13 validated, 57 unvalidated. P10 requires a *dated,
per-model* decision — keep-and-plan, orchestration-surface, or remove — and
requires it to be re-generable rather than hand-written, because the registry
changes whenever a model card or a validation run moves.

Classification rules (transparent, and re-derived on every run):

* ``validated`` -> ``published`` — nothing to do.
* ``unvalidated`` with a computational purpose (model_type is a science type, or
  the purpose names a calculation) -> ``keep_and_plan_validation`` — the model
  computes something real; the gap is independent validation evidence.
* ``unvalidated`` orchestration/UX surface (recommendation, orchestrator,
  dashboard, pipeline, scenario manager) -> ``keep_and_plan_explainability`` —
  these route or present results; they need an explainability/provenance
  contract, not a scientific reference.
* Everything else -> ``keep_and_plan_validation`` (the default never silently
  drops a model).

Nothing is proposed for removal: the registry reports zero models without an
implementation, and removing a declared model is a product decision that needs
evidence the model serves nothing — which this script does not have.

Usage::

    python tools/engine_model_triage.py [--out docs/project/ENGINE-MODEL-TRIAGE.md]
"""

from __future__ import annotations

import argparse
from collections import Counter
from datetime import UTC, datetime
from pathlib import Path

from engine.models.registry import get_model, list_models

#: Types whose models compute a scientific quantity and therefore need
#: validation evidence before their output may be published as science.
_SCIENCE_TYPES = {
    "soil_physics",
    "soil_chemistry",
    "hydrology",
    "climate",
    "crop",
    "agronomy",
    "carbon",
    "erosion",
    "ecosystem",
    "economics",
    "irrigation",
    "groundwater",
    "water_quality",
    "remote_sensing",
    "statistics",
}

#: Purpose markers that mean "this layer routes or presents, it does not
#: compute science".
_ORCHESTRATION_MARKERS = (
    "orchestrat",
    "recommend",
    "dashboard",
    "pipeline",
    "scenario",
    "chain",
    "compare",
)


def _classify(model) -> tuple[str, str]:
    """Return (decision, why) for one model spec."""
    if model.validation_status.value == "validated":
        return "published", "validation evidence on record"

    model_type = str(getattr(model, "model_type", "") or "").lower()
    purpose = (model.purpose or "").lower()

    if (
        any(marker in purpose for marker in _ORCHESTRATION_MARKERS)
        and model_type not in _SCIENCE_TYPES
    ):
        return (
            "keep_and_plan_explainability",
            "routes/presents results — needs an explainability + provenance contract",
        )
    if model_type in _SCIENCE_TYPES or any(
        word in purpose for word in ("calculate", "compute", "estimate", "predict", "measure")
    ):
        return (
            "keep_and_plan_validation",
            "computes a quantity — needs independent reference validation",
        )
    return (
        "keep_and_plan_validation",
        "no evidence either way — default keeps the model and asks for evidence",
    )


def build_rows() -> list[dict]:
    rows = []
    for model_id in list_models():
        model = get_model(model_id)
        decision, why = _classify(model)
        rows.append(
            {
                "model_id": model.model_id,
                "domain": model.domain,
                "model_type": str(model.model_type),
                "validation_status": model.validation_status.value,
                "implementation_status": model.implementation_status.value,
                "verification_status": model.verification_status.value,
                "decision": decision,
                "why": why,
            }
        )
    return rows


def render(rows: list[dict]) -> str:
    stamp = datetime.now(UTC).strftime("%Y-%m-%d")
    counts = Counter(row["decision"] for row in rows)
    lines = [
        f"# Engine model triage — {stamp}",
        "",
        f"Generated by `python tools/engine_model_triage.py` from the live registry "
        f"({len(rows)} models).",
        "",
        f"- published: **{counts['published']}**",
        f"- keep_and_plan_validation: **{counts['keep_and_plan_validation']}**",
        f"- keep_and_plan_explainability: **{counts['keep_and_plan_explainability']}**",
        f"- remove: **{counts['remove']}** (none proposed — the registry reports zero "
        "models without an implementation)",
        "",
        "| model_id | domain | type | validation | implementation | decision | why |",
        "|---|---|---|---|---|---|---|",
    ]
    for row in sorted(rows, key=lambda r: (r["decision"], r["domain"], r["model_id"])):
        lines.append(
            f"| `{row['model_id']}` | {row['domain']} | {row['model_type']} "
            f"| {row['validation_status']} | {row['implementation_status']} "
            f"| {row['decision']} | {row['why']} |"
        )
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        default="docs/project/ENGINE-MODEL-TRIAGE.md",
        help="Markdown file to write (use '-' for stdout)",
    )
    args = parser.parse_args()

    rows = build_rows()
    text = render(rows)
    if args.out == "-":
        print(text)
    else:
        Path(args.out).write_text(text, encoding="utf-8")
        print(f"wrote {args.out} ({len(rows)} models)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
