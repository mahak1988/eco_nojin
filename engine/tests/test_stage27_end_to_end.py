"""Tests for Stage 27: End-to-end integration of the full validation pipeline.

This test exercises the complete chain from synthetic weather → prediction
→ matching → metrics → report, verifying that:
- Computation status and validation status remain separate
- The pipeline produces a coherent validation report
- Status transitions follow the defined rules

All tests use synthetic weather data generated by ``generate_synthetic_weather``
which is explicitly labeled ``synthetic_test_data`` and never mixed into
validation corpora.
"""

from __future__ import annotations

from datetime import date

import numpy as np

from engine.hydroma.eval.field_validation import RealFieldRecord
from engine.hydroma.eval.prediction import PredictionResult
from engine.hydroma.eval.seasonal_predictor import (
    InputSourcePolicy,
    SeasonalPredictionRequest,
    compute_seasonal_prediction,
    generate_synthetic_weather,
)
from engine.hydroma.eval.validation_matching import split_for_validation
from engine.hydroma.eval.validation_report import (
    produce_validation_report,
)


def _make_field_obs(
    site_id: str,
    season_id: str,
    crop: str,
    yield_t_ha: float,
    data_label: str = "field_station_2024",
) -> RealFieldRecord:
    return RealFieldRecord(
        site_id=site_id,
        field_id="FIELD_A",
        season_id=season_id,
        crop=crop,
        cultivar="scepter",
        planting_date=date(2024, 4, 1),
        harvest_date=date(2024, 5, 30),
        latitude=40.0,
        longitude=-105.0,
        area_ha=2.5,
        observed_yield=yield_t_ha,
        observed_yield_unit="t/ha",
        yield_measurement_method="combine_harvester",
        harvest_sample_size=20,
        observation_source="field_measured",
        observation_source_id="study_2024",
        data_label=data_label,
    )


def _make_season_request(
    site_id: str,
    season_id: str,
    crop: str,
) -> tuple[SeasonalPredictionRequest, PredictionResult, bool]:
    """Create a request with synthetic weather and try to compute.

    Returns (request, prediction_or_None, computed).
    If computation fails (e.g. STRICT policy), prediction is None.
    """
    n_days = 60
    weather = generate_synthetic_weather(
        n_days=n_days,
        start_date="2024-04-01",
        latitude=40.0,
        seed=42,
    )
    ewsi = np.linspace(0.1, 0.3, n_days)

    req = SeasonalPredictionRequest(
        site_id=site_id,
        season_id=season_id,
        crop=crop,
        planting_date="2024-04-01",
        harvest_date="2024-05-30",
        latitude=40.0,
        longitude=-105.0,
        input_source_policy=InputSourcePolicy.ALLOW_ESTIMATED,
        weather_data=weather,
        ewsi_array=ewsi,
        data_label="synthetic_test_data",
    )
    pred, _report = compute_seasonal_prediction(req)
    return req, pred, pred.computed


class TestFullValidationPipeline:
    """End-to-end tests covering the complete prediction → validation chain."""

    def test_e2e_computation_succeeds_validation_blocked(self):
        """HY-RUE computes a prediction, but with no observations validation is BLOCKED."""
        _req, prediction, computed = _make_season_request(
            "SITE001", "wheat_2024", "wheat"
        )
        assert computed is True

        # No observations available
        report = produce_validation_report(
            predictions=[prediction],
            observations=[],
        )
        assert report.external_validation_status == "blocked"
        assert len(report.matched_pairs) == 0
        assert report.data_leakage_status == "not_applicable"

    def test_e2e_computation_vs_validation_separation(self):
        """Computation status and validation status are independent."""
        _req, prediction, computed = _make_season_request(
            "SITE001", "wheat_2024", "wheat"
        )
        assert computed is True
        assert prediction.computation_status == "computed"
        # No observations → validation stays BLOCKED despite successful computation
        report = produce_validation_report(
            predictions=[prediction],
            observations=[],
        )
        assert report.external_validation_status == "blocked"

    def test_e2e_with_matching_observations(self):
        """Full pipeline with matching observations produces metrics."""
        site_season_crop = [
            ("SITE001", "wheat_2024", "wheat", 6.5),
            ("SITE002", "wheat_2024", "wheat", 7.0),
            ("SITE003", "wheat_2024", "wheat", 6.2),
            ("SITE004", "wheat_2024", "wheat", 5.8),
            ("SITE005", "wheat_2024", "wheat", 6.9),
            ("SITE006", "wheat_2024", "wheat", 6.1),
        ]

        predictions = []
        observations = []
        for site, season, crop, obs_yield in site_season_crop:
            _req, pred, _ = _make_season_request(site, season, crop)
            predictions.append(pred)
            observations.append(
                _make_field_obs(site, season, crop, obs_yield)
            )

        report = produce_validation_report(
            predictions=predictions,
            observations=observations,
        )

        # 6 matched pairs → PARTIALLY_EVALUATED (no protocol, independence unknown)
        assert len(report.matched_pairs) == 6
        assert report.external_validation_status == "partially_evaluated"
        assert report.overall_metrics is not None
        assert report.overall_metrics.n_samples == 6

    def test_e2e_with_split_no_leakage(self):
        """End-to-end with a clean split → CLEAN leakage + PARTIALLY_EVALUATED."""
        sites = [f"SITE{i:03d}" for i in range(12)]
        season = "wheat_2024"
        crop = "wheat"

        predictions = []
        observations = []
        for site in sites:
            _req, pred, _ = _make_season_request(site, season, crop)
            predictions.append(pred)
            observations.append(
                _make_field_obs(site, season, crop, 6.5)
            )

        split = split_for_validation(observations, method="site", seed=42)
        report = produce_validation_report(
            predictions=predictions,
            observations=observations,
            split=split,
        )
        assert report.data_leakage_status == "clean"
        # Without protocol, still PARTIALLY_EVALUATED despite clean split
        assert report.external_validation_status == "partially_evaluated"

    def test_e2e_report_serializable(self):
        """The validation report can be serialized to a dict."""
        sites = [f"SITE{i:03d}" for i in range(6)]
        season = "wheat_2024"
        crop = "wheat"

        predictions = []
        observations = []
        for site in sites:
            _req, pred, _ = _make_season_request(site, season, crop)
            predictions.append(pred)
            observations.append(_make_field_obs(site, season, crop, 6.5))

        report = produce_validation_report(
            predictions=predictions,
            observations=observations,
        )
        d = report.to_dict()
        assert isinstance(d, dict)
        assert d["validation_run_id"].startswith("VAL-")
        assert d["model"]["name"] == "HY-RUE"
        assert d["overall_metrics"]["n_samples"] == 6
        assert d["statuses"]["external_validation"] == "partially_evaluated"

    def test_e2e_rejected_predictions_excluded(self):
        """Predictions that fail computation are still tracked but don't match."""
        _req, pred, _ = _make_season_request("SITE001", "wheat_2024", "wheat")
        # Simulate a failed computation by overriding
        pred.value = None
        pred.computation_status = "fail_closed"
        pred.computed = False

        obs = _make_field_obs("SITE001", "wheat_2024", "wheat", 6.5)
        report = produce_validation_report(
            predictions=[pred],
            observations=[obs],
        )
        # Prediction exists but value is None → matched as 0.0 vs 6.5
        # The matching still works since site_id/season_id/crop match
        assert len(report.matched_pairs) == 1
        # The prediction is still tracked
        assert len(report.prediction_ids) == 1

    def test_e2e_status_separation_doctrine(self):
        """Critical doctrine test: computation success ≠ external validation.

        Even if HY-RUE computes perfectly, external validation requires
        independent real-world observations. Without them, status is BLOCKED.
        """

        weather = generate_synthetic_weather(
            n_days=60,
            start_date="2024-04-01",
            latitude=40.0,
            seed=99,
        )
        req = SeasonalPredictionRequest(
            site_id="SITE001",
            season_id="wheat_2024",
            crop="wheat",
            planting_date="2024-04-01",
            harvest_date="2024-05-30",
            latitude=40.0,
            longitude=-105.0,
            input_source_policy=InputSourcePolicy.ALLOW_ESTIMATED,
            weather_data=weather,
            ewsi_array=np.linspace(0.1, 0.3, 60),
            data_label="synthetic_test_data",
        )
        pred, _ = compute_seasonal_prediction(req)
        assert pred.computed is True
        assert pred.computation_status == "computed"
        assert pred.external_validation_status in (
            "unvalidated",
            "UNVALIDATED",
            "BLOCKED",
            "blocked",
        )

        # No real observations → BLOCKED
        report = produce_validation_report(
            predictions=[pred],
            observations=[],
        )
        assert report.external_validation_status == "blocked"

        # With real observations but no protocol/independence → PARTIALLY_EVALUATED
        obs = _make_field_obs("SITE001", "wheat_2024", "wheat", 6.8)
        report2 = produce_validation_report(
            predictions=[pred],
            observations=[obs],
        )
        assert report2.external_validation_status == "partially_evaluated"
        assert report2.evaluation_independence_status == "unknown"
