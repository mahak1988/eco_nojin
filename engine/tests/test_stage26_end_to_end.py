class TestScenarioIntegration:
    """Tests connecting the seasonal predictor with the scenario layer."""

    def test_prediction_feed_to_scenario(self, base_request):
        """A PredictionResult can feed into the scenario/scoring layer."""
        from engine.hydroma.eval.prediction import PredictionResult
        from engine.hydroma.eval.scenarios import Scenario, ScenarioResult

        pred, report = compute_seasonal_prediction(base_request)
        assert isinstance(pred, PredictionResult)
        assert pred.prediction_id is not None

        scenario = Scenario(
            scenario_id="baseline",
            name="baseline",
            description="baseline run",
            input_source_config={"policy": "allow_estimated_inputs"},
        )
        sr = ScenarioResult(
            scenario=scenario,
            prediction=pred,
            input_source_used={"policy": "allow_estimated_inputs"},
        )
        assert sr.scenario.scenario_id == "baseline"
        assert sr.prediction.prediction_id == pred.prediction_id

    def test_prediction_feeds_match_hyra(self, base_request):
        """A PredictionResult can be matched against field observations."""
        from engine.hydroma.eval.field_data import (
            EvaluationDataset,
            FieldObservation,
            SeasonInfo,
            SiteInfo,
            VariableType,
        )
        from engine.hydroma.eval.prediction import match_hyra_to_observations

        pred, _ = compute_seasonal_prediction(base_request)

        site = SiteInfo(
            site_id="TEST_SITE_001",
            latitude=40.0,
            longitude=-105.0,
            elevation_m=1600.0,
            country="US",
            dataset="synthetic_test_data",
        )
        season = SeasonInfo(
            crop="wheat",
            planting_date=date(2024, 4, 1),
            harvest_date=date(2024, 5, 30),
            season_length_days=60,
        )
        obs = FieldObservation(
            site="TEST_SITE_001",
            season="wheat_2024",
            observation_id="obs1",
            variable=VariableType.YIELD,
            value=1.5,
            unit="t/ha",
            observation_date=date(2024, 5, 30),
            source="field_measured",
            quality_flag="good",
        )
        dataset = EvaluationDataset(
            name="test",
            version="1.0.0",
            sites={"TEST_SITE_001": site},
            seasons={"wheat_2024": season},
            observations=[obs],
        )

        matches = match_hyra_to_observations([pred], dataset.observations)
        assert len(matches) == 1
        m = matches[0]
        assert m.prediction_value_normalized > 0
        assert m.observed_value == pytest.approx(1.5)
        assert m.relative_error != float("inf")


